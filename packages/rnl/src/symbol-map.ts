import type { CircuitProject, StableId } from "@icm/model";
import type { BodyPortOrder } from "@icm/netlist";

import list from "./symbol-list.json";
import type { RnlOrient } from "./orientation.js";
import type { RnlPoint } from "./place.js";

/** One terminal of an RNL symbol, in the instance line's node order. */
export interface RnlTerminal {
  /** Position on the instance line, from 1. */
  n: number;
  name: string;
  /** The symbol draws a pin for it. */
  drawn: boolean;
}

/** A pin the RNL symbol draws, and the Analog Canvas pin it stands for. */
export interface RnlPin {
  terminal: number;
  acPin: string;
  /** In the RNL symbol's own frame: registered at (0, 0), y up. */
  at: RnlPoint;
  /** Exit direction in degrees, 0 right and 90 up; null when unknown. */
  dir: number | null;
}

/**
 * An RNL symbol and the Analog Canvas symbol it is drawn from.
 *
 * The list is `symbol-list.json`, generated by rnl-dev's
 * `notes/analog-canvas-rnl-import-export/build-symbol-list.mjs` from this
 * repository's component definitions. The runtime's symbol catalog is the
 * authority and this list is checked against it.
 */
export interface RnlSymbol {
  /** The RNL symbol, such as `$NMOS`. */
  symbol: string;
  /**
   * How Analog Canvas's drawing turns the symbol: `R0`, or `MX` for the
   * variants that draw it flipped top to bottom (the op-amp kinds with − on
   * top; RNL's have + on top). The export turns the part by this first.
   */
  orient: RnlOrient;
  /**
   * The row only reads other tools' files back: a standard symbol drawn
   * otherwise than Analog Canvas draws its part (the 4-input gates), or a
   * legacy appearance alias (controlled-source diamonds). The export uses
   * the canonical symbol instead. Pins are where the RNL symbol has them.
   */
  importOnly: boolean;
  /**
   * The definition whose usages the symbol draws, such as `$GROUND` for
   * `$GROUND_SYMBOL`: a virtual element, a mark or a drawing-only part. Null
   * for a device's symbol, which RNL sets on the netlist's own instance.
   */
  definition: string | null;
  /** The RNL package that defines it, such as `rnl-std-basic`. */
  package: string;
  /** The Analog Canvas symbol and variant it draws, or null for RNL-only symbols. */
  ac: string | null;
  variant: string | null;
  terminals: readonly RnlTerminal[];
  /**
   * The symbol's registration point in the Analog Canvas symbol's own frame,
   * in RNL units: RNL places the part there, Analog Canvas at its origin.
   */
  offset: RnlPoint;
  pins: readonly RnlPin[];
  /**
   * Analog Canvas pins the variant hides, with their terminals: the symbol
   * draws no pin for them, though a wire may still reach one.
   */
  undrawnPins: readonly { terminal: number; acPin: string }[];
  /**
   * The terminals in the order Analog Canvas prints its own body's ports, for
   * the parts it netlists through a body it writes itself; null otherwise.
   */
  acNetlistOrder: readonly string[] | null;
}

interface ListEntry {
  symbol: string;
  orient: RnlOrient;
  import_only?: boolean;
  definition: string | null;
  package: string;
  ac: string | null;
  variant: string | null;
  terminals: RnlTerminal[];
  offset: number[];
  pins: {
    terminal: number;
    ac_pin: string;
    at: number[];
    dir: number | null;
  }[];
  undrawn_pins: { terminal: number; ac_pin: string }[];
  ac_netlist_order: string[] | null;
}

const point = (values: readonly number[]): RnlPoint => [values[0]!, values[1]!];

export const RNL_SYMBOLS: readonly RnlSymbol[] = (list as ListEntry[]).map(
  (entry) => ({
    symbol: entry.symbol,
    orient: entry.orient,
    importOnly: entry.import_only ?? false,
    definition: entry.definition,
    package: entry.package,
    ac: entry.ac,
    variant: entry.variant,
    terminals: entry.terminals,
    offset: point(entry.offset),
    pins: entry.pins.map((pin) => ({
      terminal: pin.terminal,
      acPin: pin.ac_pin,
      at: point(pin.at),
      dir: pin.dir,
    })),
    undrawnPins: entry.undrawn_pins.map((pin) => ({
      terminal: pin.terminal,
      acPin: pin.ac_pin,
    })),
    acNetlistOrder: entry.ac_netlist_order,
  }),
);

/** The terminal an Analog Canvas pin connects, drawn or hidden by the variant. */
export function terminalOfPin(
  symbol: RnlSymbol,
  acPin: string,
): number | undefined {
  return (
    symbol.pins.find((pin) => pin.acPin === acPin)?.terminal ??
    symbol.undrawnPins.find((pin) => pin.acPin === acPin)?.terminal
  );
}

/**
 * The RNL symbol drawing an Analog Canvas symbol in a variant. A variant with
 * no symbol of its own uses the plain row. A row that only reads files back
 * draws nothing.
 */
export function rnlSymbolFor(
  symbolId: string,
  variantId?: string | null,
): RnlSymbol | undefined {
  const drawn = RNL_SYMBOLS.filter(
    (entry) => entry.ac === symbolId && !entry.importOnly,
  );
  return (
    drawn.find((entry) => entry.variant === (variantId ?? null)) ??
    drawn.find((entry) => entry.variant === null)
  );
}

/**
 * The terminal each of a body's ports meets, from the terminals in the order
 * Analog Canvas prints its block's ports. A body takes every port of its
 * block, or all but supplies it does not read, as an ideal comparator's body
 * does: its supplies, VDD and VSS, then meet their terminals by name and its
 * signals the rest in order. Null when the ports fit neither.
 */
function bodyTerminals(
  ports: readonly string[],
  order: readonly string[],
): readonly string[] | null {
  if (ports.length === order.length) return order;
  const supplies: Readonly<Record<string, string>> = { VDD: "vp", VSS: "vn" };
  const signals = order.filter(
    (terminal) => !Object.values(supplies).includes(terminal),
  );
  let next = 0;
  const terminals = ports.map((port) => supplies[port] ?? signals[next++]);
  return next === signals.length &&
    terminals.every(
      (terminal): terminal is string =>
        terminal !== undefined && order.includes(terminal),
    )
    ? terminals
    : null;
}

/**
 * The netlist port order that lets RNL symbols bind to terminal positions: each
 * body Analog Canvas writes itself, printed in its symbol's terminal order.
 * The parts calling one body must agree, and a body no mapped part calls keeps
 * its order.
 */
export function rnlBodyPortOrder(project: CircuitProject): BodyPortOrder {
  const parts = new Map<StableId, { symbolId: string; variant?: string }>();
  for (const document of project.documents)
    for (const instance of document.instances)
      parts.set(instance.id, {
        symbolId: instance.symbolId,
        ...(instance.symbolVariantId
          ? { variant: instance.symbolVariantId }
          : {}),
      });
  return ({ name, ports, instanceIds }) => {
    let wanted: readonly string[] | null = null;
    for (const id of instanceIds) {
      const part = parts.get(id);
      const entry = part && rnlSymbolFor(part.symbolId, part.variant);
      const order = entry?.acNetlistOrder;
      if (!entry || !order) continue;
      const terminals = bodyTerminals(ports, order);
      if (!terminals)
        throw new Error(
          `${entry.symbol} reads ${order.length} terminals, but ${name} has ${ports.length} ports`,
        );
      const next = entry.terminals.flatMap((terminal) =>
        ports.filter((_, index) => terminals[index] === terminal.name),
      );
      if (wanted && wanted.join(" ") !== next.join(" "))
        throw new Error(
          `Parts calling ${name} read its ports in different orders`,
        );
      wanted = next;
    }
    return wanted;
  };
}
