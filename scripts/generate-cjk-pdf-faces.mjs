#!/usr/bin/env node
/**
 * The CJK faces the PDF exporter embeds for characters Metropolis, the serif
 * and DejaVu Sans lack (#2179), cut from Noto Sans SC, and the table that
 * says which face holds a character:
 *
 *   node scripts/generate-cjk-pdf-faces.mjs [--check]
 *
 * Downloads the pinned variable source and checks its SHA-256. Needs Python's
 * fontTools (the committed faces were written with fontTools 4.62.1); the
 * cut itself is scripts/generate-cjk-pdf-faces.py. --check rebuilds into a
 * temporary directory and fails when a committed file differs.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "packages/exporters/fonts/cjk");
const table = "packages/exporters/src/cjk-pdf-faces.generated.ts";
const SOURCE_URL =
  "https://github.com/google/fonts/raw/5bb28733cec313b63fbd415b574b5ae35c8aa8b8/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf";
const SOURCE_SHA256 =
  "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da";

const check = process.argv.includes("--check");
const work = mkdtempSync(join(tmpdir(), "cjk-pdf-faces-"));
try {
  const response = await fetch(SOURCE_URL);
  if (!response.ok)
    throw new Error(`Cannot download Noto Sans SC (HTTP ${response.status})`);
  const source = Buffer.from(await response.arrayBuffer());
  const digest = createHash("sha256").update(source).digest("hex");
  if (digest !== SOURCE_SHA256)
    throw new Error(`Noto Sans SC has SHA-256 ${digest}, not ${SOURCE_SHA256}`);
  const sourcePath = join(work, "NotoSansSC.ttf");
  writeFileSync(sourcePath, source);
  const directory = check ? work : output;
  const cut = spawnSync(
    "python3",
    [join(root, "scripts/generate-cjk-pdf-faces.py"), sourcePath, directory],
    { encoding: "utf8", maxBuffer: 1 << 24 },
  );
  if (cut.status !== 0)
    throw new Error(`Cannot cut the CJK faces: ${cut.stderr || cut.error}`);
  const { common, starts, faces } = JSON.parse(cut.stdout);
  const letters = [...Array(faces).keys()].map((index) =>
    String.fromCharCode(65 + index),
  );
  const content = await format(
    [
      "// Generated by scripts/generate-cjk-pdf-faces.mjs. Do not edit.",
      ...letters.map(
        (letter) =>
          `import face${letter} from "../fonts/cjk/ICMCJK-${letter}.ttf?url";`,
      ),
      "",
      `export const cjkFaceUrls = [${letters.map((letter) => `face${letter}`).join(", ")}];`,
      `export const cjkCommonGlyphs = ${JSON.stringify(common)};`,
      `export const cjkFaceStarts = [${starts.map((point) => `0x${point.toString(16)}`).join(", ")}];`,
      "",
    ].join("\n"),
    { parser: "typescript" },
  );
  const stale = [];
  if (check) {
    const committed = readdirSync(output).filter((name) =>
      name.endsWith(".ttf"),
    );
    const built = letters.map((letter) => `ICMCJK-${letter}.ttf`);
    if (committed.join() !== built.join()) stale.push(output);
    for (const name of built)
      if (
        !committed.includes(name) ||
        !readFileSync(join(work, name)).equals(readFileSync(join(output, name)))
      )
        stale.push(name);
    if (readFileSync(join(root, table), "utf8") !== content) stale.push(table);
  } else writeFileSync(join(root, table), content);
  if (stale.length) {
    console.error(
      `CJK PDF faces differ from their source: ${stale.join(", ")}. Run node scripts/generate-cjk-pdf-faces.mjs`,
    );
    process.exitCode = 1;
  } else
    console.log(`CJK PDF faces: ${faces} ${check ? "current" : "written"}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
