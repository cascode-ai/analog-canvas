import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { format } from "prettier";
import {
  loadComponentLibrary,
  definitionRoot,
  jsonSource,
  writeComponentProjection,
} from "./lib/component-library.mjs";
import {
  deriveDepletionMosSymbol,
  deriveDmosSymbol,
} from "./lib/derived-mos-symbol.mjs";
import { isDeepStrictEqual } from "node:util";

const { index, byId } = await loadComponentLibrary();
const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
for (const id of index.extendedEntries) {
  const component = byId.get(id);
  if (!component.catalog.derivedFrom) continue;
  const base = byId.get(component.catalog.derivedFrom);
  const symbol =
    component.catalog.derivation === "mos-drift-region"
      ? deriveDmosSymbol(base?.symbol, id, component.symbol.name)
      : component.catalog.derivation === "mos-depletion-channel"
        ? deriveDepletionMosSymbol(base?.symbol, id, component.symbol.name)
        : (() => {
            throw new Error(`Unsupported derivation for ${id}`);
          })();
  if (!isDeepStrictEqual(component.symbol, symbol)) {
    if (check)
      throw new Error(
        `${id}: derived MOS geometry is stale; run pnpm components:generate`,
      );
    await writeComponentProjection(
      resolve(definitionRoot, `${id}.json`),
      await jsonSource(symbol),
    );
    component.symbol = symbol;
  }
}
const outputs = [
  [
    "packages/devices/src/components.generated.ts",
    `
// Generated by scripts/generate-component-library.mjs. Do not edit.
// Source: packages/components/definitions/<symbol-id>.json (electrical).
import type { DeviceDescriptor } from "./contract.js";
export const componentDeviceDescriptors: readonly DeviceDescriptor[] = ${JSON.stringify(index.deviceOrder.map((id) => byId.get(id).electrical))};
`,
  ],
  [
    "packages/symbols/src/expanded-components.generated.ts",
    `
// Generated by scripts/generate-component-library.mjs. Do not edit.
// Source: packages/components/definitions/<symbol-id>.json (symbol/catalog).
import type { SymbolDefinition } from "./schema.js";
import type { ExpandedDeviceCatalogEntry } from "./expanded-device-catalog.js";
export const expandedComponentSymbols: readonly SymbolDefinition[] = ${JSON.stringify(index.extendedEntries.map((id) => byId.get(id).symbol))};
export const expandedComponentCatalogEntries: readonly ExpandedDeviceCatalogEntry[] = ${JSON.stringify(
      index.extendedEntries.map((id) => {
        const { library, derivedFrom, derivation, ...entry } =
          byId.get(id).catalog;
        return entry;
      }),
    )};
`,
  ],
];
for (const [path, source] of outputs) {
  const generated = await format(source, { parser: "typescript" });
  const target = resolve(root, path);
  if (check) {
    if ((await readFile(target, "utf8").catch(() => null)) !== generated)
      throw new Error(`${path} is stale; run pnpm components:generate`);
  } else await writeFile(target, generated);
}
console.log(
  `${check ? "Validated" : "Generated"} ${byId.size} components and ${index.deviceOrder.length} electrical descriptors`,
);
